def test_fastapi_endpoints(monkeypatch: pytest.MonkeyPatch) -> None:
    from app.auth import create_mock_oidc_token
    from app.config import get_settings

    monkeypatch.setattr(get_settings(), "app_env", "local")
    mock_token = create_mock_oidc_token("hitl-chatbot-sa@test.iam.gserviceaccount.com")
    client = TestClient(app, headers={"Authorization": f"Bearer {mock_token}"})

    # 1. Health check
    resp_health = client.get("/health")
    assert resp_health.status_code == 200
    assert resp_health.json()["status"] == "healthy"

    # 2. Case A chat
    resp_chat_a = client.post("/api/chat", json={"message": "what changed in latest rollout?"})
    assert resp_chat_a.status_code == 200
    data_a = resp_chat_a.json()
    assert data_a["type"] == "deployments"
    assert "Revision: 89" in data_a["text"]

    # 3. Case B chat (Draft generation)
    resp_chat_b = client.post(
        "/api/chat",
        json={"message": "file a JIRA ticket for latest ip-health-snow alert in test-project"},
    )
    assert resp_chat_b.status_code == 200
    data_b = resp_chat_b.json()
    assert data_b["type"] == "draft_ticket"
    signed_token = data_b["signed_token"]
    assert signed_token is not None

    # 4. Approval endpoint
    resp_appr = client.post("/api/chat/approve", json={"signed_token": signed_token})
    assert resp_appr.status_code == 200
    appr_data = resp_appr.json()
    assert appr_data["type"] == "issue_created"
    assert appr_data["result"]["issue_key"].startswith("AMJTEST-")


def test_fastapi_requester_authorization_enforced(monkeypatch: pytest.MonkeyPatch) -> None:
    from app.auth import create_mock_oidc_token
    from app.config import get_settings

    monkeypatch.setattr(get_settings(), "app_env", "local")
    mock_token = create_mock_oidc_token("hitl-chatbot-sa@test.iam.gserviceaccount.com")
    client = TestClient(app, headers={"Authorization": f"Bearer {mock_token}"})

    # 1. Draft generated by user U_ORIGINAL
    resp_chat = client.post(
        "/api/chat",
        json={
            "message": "file a JIRA ticket for latest ip-health-snow alert in test-project",
            "user_id": "U_ORIGINAL",
            "session_id": "authz-session-api",
        },
    )
    assert resp_chat.status_code == 200
    token = resp_chat.json()["signed_token"]
    assert token is not None

    # 2. Imposter user U_IMPOSTER rejected with 403 Forbidden
    resp_reject = client.post(
        "/api/chat/approve",
        json={"signed_token": token, "approver_id": "U_IMPOSTER"},
    )
    assert resp_reject.status_code == 403
    assert "not authorized" in resp_reject.json()["detail"].lower()
    assert "U_IMPOSTER" in resp_reject.json()["detail"]
    assert "U_ORIGINAL" in resp_reject.json()["detail"]

    # 3. Legitimate user U_ORIGINAL approved with 200 OK
    resp_approve = client.post(
        "/api/chat/approve",
        json={"signed_token": token, "approver_id": "U_ORIGINAL"},
    )
    assert resp_approve.status_code == 200
    assert resp_approve.json()["type"] == "issue_created"


def test_agent_runner_requester_authorization() -> None:
    runner = ChatbotAgentRunner()
    turn = runner.process_turn(
        user_message="file a JIRA ticket for latest ip-health-snow alert in test-project",
        session_id="authz-session-runner",
        user_id="U_SLACK_REQ",
    )
    assert turn["type"] == "draft_ticket"
    token = turn["signed_token"]
    assert "Requester:       U_SLACK_REQ" in turn["text"]

    # Imposter approval raises ValueError
    with pytest.raises(ValueError, match="not authorized"):
        runner.execute_approval(token, approver_id="U_SLACK_OTHER")

    # Requester approval succeeds
    res = runner.execute_approval(token, approver_id="U_SLACK_REQ")
    assert res["type"] == "issue_created"
    assert res["result"]["issue_key"].startswith("AMJTEST-")


